/**
 * Letting a second person into a notebook.
 *
 * Three steps by three parties, and the split is the point: the owner issues an
 * invitation naming who it is for, the invitee proves possession of the secret
 * with their real keys, and the owner grants. Neither side can do the other's
 * half, and the name the invitee is admitted under comes from the invitation
 * the owner signed rather than from anything the invitee sends.
 *
 * The grant is where three layers compose. It writes an admission (identity), a
 * fresh epoch sealed to the joiner (content keys), and a capability (authority)
 * in one transaction - because a peer that saw any one of those without the
 * others would see a member who cannot read, or a key held by someone with no
 * standing to use it.
 */

import * as Y from "yjs"

import { issueCapability, type Ability, type Capability } from "@/lib/authz"
import type { Bytes, SigningKey } from "@/lib/crypto"
import {
  createInvitation,
  grantFromRedemption,
  putDeviceRecord,
  putInvitation,
  putRedemption,
  redeemInvitation,
  type Invitation,
  type Redemption,
} from "@/lib/directory"
import type { DeviceIdentity } from "@/lib/identity"
import { signEpochRecord } from "@/lib/membership"

import { readCapabilities } from "./capabilities"
import {
  putEpochRecord,
  putSealedKeys,
  readNotebookKeys,
  restoreDomainAdmin,
} from "./notebook-keys"
import { resourceIdFor, workspaceIdFor } from "./notebook-workspace"

/** Default life of an invitation. Long enough to hand over, short enough to lapse. */
export const INVITATION_TTL_MS = 7 * 24 * 60 * 60 * 1000
/** Default life of a member's capability. */
export const MEMBER_GRANT_TTL_MS = 365 * 24 * 60 * 60 * 1000

export interface InviteOptions {
  doc: Y.Doc
  notebookId: string
  /** The owner. Invitations are admin-only by construction. */
  admin: { signingKey: SigningKey; did: string }
  /** Generated by the caller so it can be handed over out of band. */
  secret: Bytes
  label: string
  member?: string
  now?: number
  ttlMs?: number
}

export async function inviteToNotebook(options: InviteOptions): Promise<Invitation> {
  const invitation = await createInvitation({
    adminSigningKey: options.admin.signingKey,
    adminDid: options.admin.did,
    secret: options.secret,
    member: options.member ?? `member:${options.label.trim().toLowerCase().replace(/\s+/g, "-")}`,
    label: options.label,
    workspace: workspaceIdFor(options.notebookId),
    ...(options.now === undefined ? {} : { issuedAt: options.now }),
    ttlMs: options.ttlMs ?? INVITATION_TTL_MS,
  })
  putInvitation(options.doc, invitation)
  return invitation
}

export interface RedeemOptions {
  doc: Y.Doc
  secret: Bytes
  device: DeviceIdentity
  now?: number
}

/**
 * Claim an invitation.
 *
 * Publishes the invitee's own device record alongside the proof, because the
 * grant verifies the proof against those exact keys - sending the proof without
 * the record would leave the owner nothing to admit.
 */
export async function redeemIntoNotebook(options: RedeemOptions): Promise<Redemption> {
  const redemption = await redeemInvitation({
    secret: options.secret,
    record: options.device.record,
    ...(options.now === undefined ? {} : { redeemedAt: options.now }),
  })
  options.doc.transact(() => {
    putDeviceRecord(options.doc, options.device.record)
    putRedemption(options.doc, redemption)
  })
  return redemption
}

/** The owner's root, which a member's capability is issued against. */
export async function findOwnerRoot(
  doc: Y.Doc,
  owner: string,
  resource: string,
  now: number = Date.now(),
): Promise<Capability | null> {
  for (const capability of await readCapabilities(doc)) {
    const { iss, aud, rsc, can, prf, nbf, exp } = capability.payload
    if (iss !== owner || aud !== owner || prf !== null) continue
    if (rsc !== resource || can !== "admin") continue
    if (now < nbf || now >= exp) continue
    return capability
  }
  return null
}

export interface AdmitOptions {
  doc: Y.Doc
  notebookId: string
  /** The owner, who must hold the root and be able to open the current key. */
  owner: DeviceIdentity
  invitation: Invitation
  redemption: Redemption
  /** What the new member may do. Read unless said otherwise. */
  ability?: Ability
  now?: number
  ttlMs?: number
}

export interface Admission {
  member: string
  /** Epoch cut for this join. Existing members derive it; the joiner is sealed to. */
  epoch: number
  capability: Capability
}

/**
 * Grant membership: identity, keys and authority together.
 *
 * Every check that can refuse runs before anything is written, so a failed
 * admission leaves the document exactly as it was rather than half-admitting
 * somebody.
 */
export async function admitFromRedemption(options: AdmitOptions): Promise<Admission> {
  const now = options.now ?? Date.now()
  const resource = resourceIdFor(options.notebookId)
  const ownerDid = options.owner.did

  const root = await findOwnerRoot(options.doc, ownerDid, resource, now)
  if (!root) {
    throw new Error("the owner holds no valid root capability for this notebook")
  }

  // Identity: admin-gated, and refuses a spent invitation.
  const admission = await grantFromRedemption({
    adminSigningKey: options.owner.signingKey,
    adminDid: ownerDid,
    invitation: options.invitation,
    redemption: options.redemption,
    trustedAdminDids: [ownerDid],
    priorRedemptions: redemptionsInDoc(options.doc, options.invitation.invitationId),
    now,
  })

  // Content keys: a chain epoch, so only the joiner needs a sealed copy.
  const keys = await readNotebookKeys({
    doc: options.doc,
    notebookId: options.notebookId,
    device: options.owner,
    owner: ownerDid,
    now,
  })
  const domain = await restoreDomainAdmin(keys)
  if (!domain) {
    throw new Error("cannot admit: this device cannot open the notebook's current key")
  }
  const cut = await domain.addMember(
    { sealingDid: options.redemption.sealingDid },
    { createdAt: now },
  )
  const signedEpoch = await signEpochRecord(cut.record, options.owner.signingKey, ownerDid)

  // Authority: attenuated from the owner's root, non-delegable by default.
  const capability = await issueCapability({
    signingKey: options.owner.signingKey,
    issuer: ownerDid,
    audience: options.redemption.did,
    resource,
    ability: options.ability ?? "read",
    depth: 0,
    proof: root.cid,
    notBefore: now,
    expiresAt: Math.min(now + (options.ttlMs ?? MEMBER_GRANT_TTL_MS), root.payload.exp),
  })

  options.doc.transact(() => {
    putDeviceRecord(options.doc, options.redemption.record)
    options.doc.getMap("directory:admissions").set(admission.did, admission)
    putEpochRecord(options.doc, signedEpoch)
    putSealedKeys(options.doc, cut.sealed)
    options.doc.getMap<string>("workspace:capabilities").set(capability.cid, capability.token)
  })

  return { member: admission.member, epoch: cut.record.epoch, capability }
}

/**
 * Every redemption in the document.
 *
 * The directory stores these as an array per invitation rather than one entry
 * each, because a *second* redemption is the signal that an invitation was
 * reused - overwriting would hide exactly what single-use enforcement needs.
 */
function allRedemptions(doc: Y.Doc): Redemption[] {
  const out: Redemption[] = []
  for (const [, entries] of doc.getMap<Redemption[]>("directory:redemptions").entries()) {
    if (Array.isArray(entries)) out.push(...entries)
  }
  return out
}

/** Redemptions already recorded for an invitation, for the single-use check. */
export function redemptionsInDoc(doc: Y.Doc, invitationId: string): Redemption[] {
  return allRedemptions(doc).filter((redemption) => redemption.invitationId === invitationId)
}

/** Redemptions with no admission yet - what an owner is being asked to approve. */
export function pendingRedemptions(doc: Y.Doc): Redemption[] {
  const admitted = new Set(doc.getMap("directory:admissions").keys())
  return allRedemptions(doc).filter(
    (redemption) => redemption.did && !admitted.has(redemption.did),
  )
}

/** Invitations this notebook has issued, newest first. */
export function invitationsInDoc(doc: Y.Doc): Invitation[] {
  const out: Invitation[] = []
  for (const [id, invitation] of doc.getMap<Invitation>("directory:invitations").entries()) {
    if (invitation?.invitationId === id) out.push(invitation)
  }
  return out.sort((a, b) => b.issuedAt - a.issuedAt)
}
