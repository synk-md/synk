/**
 * Letting a second person into a notebook.
 *
 * Three steps by three parties, and the split is the point: the owner issues an
 * invitation naming who it is for, the invitee proves possession of the secret
 * with their real keys, and the owner grants. Neither side can do the other's
 * half, and the name the invitee is admitted under comes from the invitation
 * the owner signed rather than from anything the invitee sends.
 *
 * The grant is where three layers compose. It writes an admission (identity), a
 * fresh epoch sealed to the joiner (content keys), and a capability (authority)
 * in one transaction - because a peer that saw any one of those without the
 * others would see a member who cannot read, or a key held by someone with no
 * standing to use it.
 */

import * as Y from "yjs"

import { issueCapability, type Ability, type Capability } from "@/lib/authz"
import type { Bytes, SigningKey } from "@/lib/crypto"
import {
  createInvitation,
  grantFromRedemption,
  invitationIdFromSecret,
  isInvitationExpired,
  putInvitationRevocation,
  revokeInvitation,
  revokedInvitationIds,
  type InvitationRevocation,
  putDeviceRecord,
  putInvitation,
  putRedemption,
  redeemInvitation,
  verifyInvitation,
  type Invitation,
  type Redemption,
} from "@/lib/directory"
import type { DeviceIdentity } from "@/lib/identity"
import { signEpochRecord } from "@/lib/membership"

import { readCapabilities } from "./capabilities"
