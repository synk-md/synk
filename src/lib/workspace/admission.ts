/** Default life of an invitation. Long enough to hand over, short enough to lapse. */
export const INVITATION_TTL_MS = 7 * 24 * 60 * 60 * 1000
/** Default life of a member's capability. */
export const MEMBER_GRANT_TTL_MS = 365 * 24 * 60 * 60 * 1000

export interface InviteOptions {
  doc: Y.Doc
  notebookId: string
  /** The owner, or one of their own linked devices. Invitations are admin-only by construction. */
  admin: { signingKey: SigningKey; did: string }
  /** Generated by the caller so it can be handed over out of band. */
  secret: Bytes
  label: string
  member?: string
  now?: number
  ttlMs?: number
}

export async function inviteToNotebook(options: InviteOptions): Promise<Invitation> {
  // Named in the invitation whenever there is one, so whoever joins checks the
  // notebook against the owner and not against the device that invited them.
  const { ownership } = await readNotebookWorkspace({ doc: options.doc, notebookId: options.notebookId })
  const invitation = await createInvitation({
    adminSigningKey: options.admin.signingKey,
    adminDid: options.admin.did,
    secret: options.secret,
    member: options.member ?? `member:${options.label.trim().toLowerCase().replace(/\s+/g, "-")}`,
    label: options.label,
    workspace: workspaceIdFor(options.notebookId),
    ...(ownership.owner === null ? {} : { owner: ownership.owner }),
    ...(options.now === undefined ? {} : { issuedAt: options.now }),
    ttlMs: options.ttlMs ?? INVITATION_TTL_MS,
  })
  putInvitation(options.doc, invitation)
  return invitation
}

export interface RedeemOptions {
  doc: Y.Doc
  secret: Bytes
  device: DeviceIdentity
  now?: number
}

/**
 * Claim an invitation.
 *
 * Publishes the invitee's own device record alongside the proof, because the
 * grant verifies the proof against those exact keys - sending the proof without
 * the record would leave the owner nothing to admit.
 */
export async function redeemIntoNotebook(options: RedeemOptions): Promise<Redemption> {
  const redemption = await redeemInvitation({
    secret: options.secret,
    record: options.device.record,
    ...(options.now === undefined ? {} : { redeemedAt: options.now }),
  })
  options.doc.transact(() => {
    putDeviceRecord(options.doc, options.device.record)
    putRedemption(options.doc, redemption)
  })
  return redemption
}

/** Invitation revocations recorded in this notebook. */
export function invitationRevocationsInDoc(doc: Y.Doc): InvitationRevocation[] {
  return valuesIn<InvitationRevocation>(doc, DIRECTORY_MAPS.invitationRevocations).filter(
    (revocation) => typeof revocation.invitationId === "string",
  )
}

/** Who may act as admin here: the owner, their own linked devices, and what was kept of former ones. */
export async function notebookAdmins(doc: Y.Doc, owner: string): Promise<AdminTrust> {
  const directory = await readDirectory(doc, [owner])
  return { dids: directory.admins, kept: directory.kept }
}

/** Invitations an admin has taken back, verified against the owner and their devices. */
export async function withdrawnInvitations(
  doc: Y.Doc,
  owner: string,
): Promise<Set<string>> {
  return revokedInvitationIds(invitationRevocationsInDoc(doc), invitationsInDoc(doc), await notebookAdmins(doc, owner))
}

export interface CancelInvitationOptions {
  doc: Y.Doc
  admin: { signingKey: SigningKey; did: string }
  invitation: Invitation
  reason?: string
  now?: number
}

/**
 * Take an invitation back.
 *
 * The recovery path when a code is lost, and the reason losing one is not
 * permanent: the secret cannot be recovered by anybody, so the only safe answer
 * is to make the old invitation unusable and issue a new one.
 */
export async function cancelInvitation(
  options: CancelInvitationOptions,
): Promise<InvitationRevocation> {
  const revocation = await revokeInvitation({
    signingKey: options.admin.signingKey,
    admin: options.admin.did,
    invitation: options.invitation,
    ...(options.reason === undefined ? {} : { reason: options.reason }),
    ...(options.now === undefined ? {} : { revokedAt: options.now }),
  })
  putInvitationRevocation(options.doc, revocation)
  return revocation
}

export interface InvitationMatch {
  invitation: Invitation
  /** The admin who signed it. What the notebook's genesis must agree with. */
  expectedOwner: string
}

/**
 * Find the invitation a code belongs to, and take the owner from it.
 *
 * The lookup is what makes this trustworthy: the invitation's id is *derived
 * from the secret*, so only the holder of that code can compute which record to
 * look for, and only the admin who issued it could have signed a record filed
 * there. A joiner arriving by link therefore learns the expected owner from the
 * invitation itself rather than taking the notebook's word for it.
 *
 * What it does not do is make the code an anchor for ownership. Somebody
 * holding both the link and the code could overwrite the record and name
 * themselves - but somebody holding both could already redeem as the invitee,
 * so this grants them nothing new. What it buys is that a *disagreement*
 * between the invitation and the genesis becomes visible instead of silently
 * resolving in the document's favour.
 */
export async function matchInvitation(
  doc: Y.Doc,
  secret: Bytes,
  now: number = Date.now(),
): Promise<InvitationMatch | null> {
  const invitationId = await invitationIdFromSecret(secret)
  const invitation = invitationsInDoc(doc).find(
    (candidate) => candidate.invitationId === invitationId,
  )
  if (!invitation) return null

  // Signed by the admin it names. Not a claim about who the owner is yet -
  // that is settled by checking the genesis against it.
  if (!(await verifyInvitation(invitation, [invitation.admin], { now }))) return null
  return { invitation, expectedOwner: invitation.owner ?? invitation.admin }
}

/**
 * The invitation this device already redeemed here, if any.
 *
 * For somebody coming back to the link: the code is not needed twice, and the
 * invitation still names the admin to check the notebook's genesis against.
 */
export async function findOwnRedemption(
  doc: Y.Doc,
  did: string,
  now: number = Date.now(),
): Promise<InvitationMatch | null> {
  for (const invitation of invitationsInDoc(doc)) {
    if (!redemptionsInDoc(doc, invitation.invitationId).some((redemption) => redemption.did === did)) {
      continue
    }
    if (await verifyInvitation(invitation, [invitation.admin], { now })) {
      return { invitation, expectedOwner: invitation.owner ?? invitation.admin }
    }
  }
  return null
}

/** The owner's root, which a member's capability is issued against. */
export async function findOwnerRoot(
  doc: Y.Doc,
  owner: string,
  resource: string,
  now: number = Date.now(),
): Promise<Capability | null> {
  for (const capability of await readCapabilities(doc)) {
    const { iss, aud, rsc, can, prf, nbf, exp } = capability.payload
    if (iss !== owner || aud !== owner || prf !== null) continue
    if (rsc !== resource || can !== "admin") continue
    if (now < nbf || now >= exp) continue
    return capability
  }
  return null
}

export interface AdmitOptions {
  doc: Y.Doc
  notebookId: string
  /**
   * The device admitting: the owner, or one of the owner's own linked devices,
   * which must be able to open the current key.
   */
  owner: DeviceIdentity
  /** The notebook's owner, whose root it issues under, when that is not `owner` itself. */
  ownerDid?: string
  invitation: Invitation
  redemption: Redemption
  /** What the new member may do. Read unless said otherwise. */
  ability?: Ability
  now?: number
  ttlMs?: number
}

export interface Admission {
  member: string
  /** Epoch cut for this join. Existing members derive it; the joiner is sealed to. */
  epoch: number
  capability: Capability
}

/**
 * Grant membership: identity, keys and authority together.
 *
 * Every check that can refuse runs before anything is written, so a failed
 * admission leaves the document exactly as it was rather than half-admitting
 * somebody.
 */
export async function admitFromRedemption(options: AdmitOptions): Promise<Admission> {
  const now = options.now ?? Date.now()
  const resource = resourceIdFor(options.notebookId)
  const ownerDid = options.ownerDid ?? options.owner.did
  const admin = options.owner

  const root = await findOwnerRoot(options.doc, ownerDid, resource, now)
  if (!root) {
    throw new Error("the owner holds no valid root capability for this notebook")
  }

  // Checked here rather than left to `grantFromRedemption`, which knows about
  // signatures and expiry but nothing about withdrawal.
  const withdrawn = await withdrawnInvitations(options.doc, ownerDid)
  if (withdrawn.has(options.invitation.invitationId)) {
    throw new Error("this invitation was cancelled; issue a new one instead")
  }

  // Identity: admin-gated, and refuses a spent invitation.
  const admission = await grantFromRedemption({
    adminSigningKey: admin.signingKey,
    adminDid: admin.did,
    invitation: options.invitation,
    redemption: options.redemption,
    trustedAdminDids: await notebookAdmins(options.doc, ownerDid),
    priorRedemptions: redemptionsInDoc(options.doc, options.invitation.invitationId),
    now,
  })

  // Content keys: a chain epoch, so only the joiner needs a sealed copy.
  const keys = await readNotebookKeys({
    doc: options.doc,
    notebookId: options.notebookId,
    device: admin,
    owner: ownerDid,
    now,
  })
  const domain = await restoreDomainAdmin(keys)
  if (!domain) {
    throw new Error("cannot admit: this device cannot open the notebook's current key")
  }
  const cut = await domain.addMember(
    { sealingDid: options.redemption.sealingDid },
    { createdAt: now },
  )
  const signedEpoch = await signEpochRecord(cut.record, admin.signingKey, admin.did)

  // Authority: attenuated from the owner's root, non-delegable by default. A
  // linked device of the owner's issues it as the owner.
  const capability = await issueCapability({
    signingKey: admin.signingKey,
    issuer: admin.did,
    audience: options.redemption.did,
    resource,
    ability: options.ability ?? "read",
    depth: 0,
    proof: root.cid,
    notBefore: now,
    expiresAt: Math.min(now + (options.ttlMs ?? MEMBER_GRANT_TTL_MS), root.payload.exp),
  })

  options.doc.transact(() => {
    putDeviceRecord(options.doc, options.redemption.record)
    putAdmission(options.doc, admission)
    putEpochRecord(options.doc, signedEpoch)
    putSealedKeys(options.doc, cut.sealed)
    options.doc.getMap<string>("workspace:capabilities").set(capability.cid, capability.token)
  })

  return { member: admission.member, epoch: cut.record.epoch, capability }
}

/**
 * Every redemption in the document.
 *
 * The directory stores these as an array per invitation rather than one entry
 * each, because a *second* redemption is the signal that an invitation was
 * reused - overwriting would hide exactly what single-use enforcement needs.
 */
function allRedemptions(doc: Y.Doc): Redemption[] {
  return redemptionsIn(doc)
}

/** Redemptions already recorded for an invitation, for the single-use check. */
export function redemptionsInDoc(doc: Y.Doc, invitationId: string): Redemption[] {
  return allRedemptions(doc).filter((redemption) => redemption.invitationId === invitationId)
}

/**
 * Whether the device behind each admission is still in.
 *
 * Unverified, like everything here: these decide what to show and which
 * connections to open, never who may do anything. Times compared are all the
 * owner's own, so one device's clock running ahead cannot strand a request.
 */
function standing(doc: Y.Doc) {
  // The latest of each, by its own time: several may be on file for one device.
  const latest = <T extends { did?: string }>(name: string, at: (record: T) => number) => {
    const out = new Map<string, T>()
    for (const record of valuesIn<T>(doc, name)) {
      if (typeof record.did !== "string") continue
      const held = out.get(record.did)
      if (!held || at(record) > at(held)) out.set(record.did, record)
    }
    return out
  }
  const admissions = latest<DeviceAdmission>(DIRECTORY_MAPS.admissions, (admission) => admission.issuedAt)
  const removals = latest<DeviceRemoval>(DIRECTORY_MAPS.removals, (removal) => removal.removedAt)
  const ended = (did: string): number | null => {
    const admission = admissions.get(did)
    const removal = removals.get(did)
    return admission && removal && removal.removedAt >= admission.issuedAt ? removal.removedAt : null
  }
  const invitations = new Map(invitationsInDoc(doc).map((invitation) => [invitation.invitationId, invitation]))

  const links = latest<{ did?: string; parent?: string; issuedAt?: number }>(DIRECTORY_MAPS.links, (link) => link.issuedAt ?? 0)
  const unlinked = latest<{ did?: string; revokedAt?: number }>(DIRECTORY_MAPS.linkRevocations, (revocation) => revocation.revokedAt ?? 0)

  return {
    live: () => {
      const admitted = [...admissions.keys()].filter((did) => ended(did) === null)
      const standing = new Set(admitted)
      // Another of a member's own devices holds the notebook too.
      const linked = [...links.entries()]
        .filter(([, link]) => typeof link.parent === "string" && standing.has(link.parent))
        // Taken back out by its member: a lost phone holds nothing any more.
        .filter(([did, link]) => (unlinked.get(did)?.revokedAt ?? -1) < (link.issuedAt ?? 0))
        .map(([did]) => did)
      return [...admitted, ...linked]
    },
    /** Granted, or granted and since removed. Either way, not waiting on anyone. */
    answered: (redemption: Redemption): boolean => {
      if (!admissions.has(redemption.did)) return false
      const removedAt = ended(redemption.did)
      if (removedAt === null) return true
      // Only a request made under a later invitation is somebody asking again.
      const invitation = invitations.get(redemption.invitationId)
      return !(invitation && invitation.issuedAt > removedAt)
    },
  }
}

/** Redemptions with no answer yet - what an owner is being asked to approve. */
export function pendingRedemptions(doc: Y.Doc): Redemption[] {
  const { answered } = standing(doc)
  return allRedemptions(doc).filter((redemption) => redemption.did && !answered(redemption))
}

/**
 * Is anyone still expected to join?
 *
 * True while an unexpired invitation has not yet produced an admitted device.
 * The notebook's index room has to be connected for that whole window, because
 * the redemption and the grant both travel through it - and link sharing, which
 * is what otherwise decides whether the room is joined, has nothing to do with
 * whether someone was invited.
 */
export function hasOutstandingInvitations(doc: Y.Doc, now: number = Date.now()): boolean {
  const { answered } = standing(doc)
  const cancelled = new Set(
    invitationRevocationsInDoc(doc).map((revocation) => revocation.invitationId),
  )
  for (const invitation of invitationsInDoc(doc)) {
    if (isInvitationExpired(invitation, now)) continue
    if (cancelled.has(invitation.invitationId)) continue
    const redemptions = redemptionsInDoc(doc, invitation.invitationId)
    if (redemptions.length === 0) return true
    if (redemptions.some((redemption) => !answered(redemption))) return true
  }
  return false
}

/**
 * Is this notebook held by any device besides the founder's - another member,
 * or another device of a member, the founder's own included?
 *
 * Membership and link sharing are different questions. A private notebook
 * shared with named members still has to sync - to them - so this is what
 * decides whether the collaboration transport runs, not the link setting.
 *
 * Counts devices, since the founder self-admits when the notebook is created:
 * one admission is a notebook nobody has joined.
 */
export function hasAdmittedMembers(doc: Y.Doc): boolean {
  return standing(doc).live().length > 1
}

/**
 * Invitations that have done their job: redeemed, and the redeeming device
 * admitted.
 *
 * Distinct from cancelled and from expired, because all three stop an
 * invitation being outstanding for different reasons and a person reading the
 * list wants to know which. This one means someone joined, and the record of
 * that is the member list.
 */
export function grantedInvitationIds(doc: Y.Doc): Set<string> {
  const { answered } = standing(doc)
  const granted = new Set<string>()
  for (const invitation of invitationsInDoc(doc)) {
    const redemptions = redemptionsInDoc(doc, invitation.invitationId)
    if (redemptions.length === 0) continue
    if (redemptions.every(answered)) {
      granted.add(invitation.invitationId)
    }
  }
  return granted
}

/** Invitations this notebook has issued, newest first. */
export function invitationsInDoc(doc: Y.Doc): Invitation[] {
  const out = new Map<string, Invitation>()
  for (const invitation of valuesIn<Invitation>(doc, DIRECTORY_MAPS.invitations)) {
    if (typeof invitation.invitationId === "string") out.set(invitation.sig, invitation)
  }
  return [...out.values()].sort((a, b) => b.issuedAt - a.issuedAt)
}
